// VsopFormula / CalcVsop: pinned astronomy.ts#L3191 / #L3255.
function vsopFormula(formula: VsopFormula, t: number, clampAngle: boolean): number {
    let tpower = 1, coord = 0;
    for (const series of formula) {
        let sum = 0;
        for (const [ampl, phas, freq] of series)
            sum += ampl * Math.cos(phas + (t * freq));
        let incr = tpower * sum;
        if (clampAngle) incr %= PI2;
        coord += incr;
        tpower *= t;
    }
    return coord;
}

/** INTERNAL: geometric Sun-centered vector in AU, J2000 mean equator. */
export function planetHelioVector(planet: Planet, tt: number): Vec3 {
    if (planet === 'earth') return earthHelioVector(tt);
    const model = models[planet], t = tt / 365250;
    const lon = vsopFormula(model[0], t, true);
    const lat = vsopFormula(model[1], t, false);
    const rad = vsopFormula(model[2], t, false);
    return vsopRotate(vsopSphereToRect(lon, lat, rad));
}

// BackdatePosition / BodyPosition / CorrectLightTravel: pinned astronomy.ts#L4170–L4313.
export function planetGeoVectorEqj(planet: Planet, tt: number, aberration = true): Vec3 {
    let ltime = tt, dt = 0;
    const fixedEarth = aberration ? null : earthHelioVector(tt);
    for (let iter = 0; iter < 10; ++iter) {
        // Backdating Earth along with the planet supplies upstream's aberration correction.
        const earth = fixedEarth ?? earthHelioVector(ltime), target = planetHelioVector(planet, ltime);
        const pos = { x: target.x-earth.x, y: target.y-earth.y, z: target.z-earth.z };
        const lt = Math.sqrt(pos.x*pos.x + pos.y*pos.y + pos.z*pos.z) / C_AUDAY;
        if (lt > 1) throw new Error('Object is too distant for light-travel solver.');
        const next = tt - lt;
        dt = Math.abs(next-ltime);
        if (dt < 1e-9) return pos;
        ltime = next;
    }
    throw new Error(`Light-travel time solver did not converge: dt = ${dt}`);
}

